# Arithmetic Operators 
x = 5
y = 10

total = x + y 
print(total)

total =  x - y
print(total)

total = x * y # Multiplication
print(total)

total = y / x # Division
print(total)

total = y // x # floor division
print(total)

total = y % x # modulus
print(total)

total = x ** 2 # exponentiation
print(total)

# Comparison Operators 
print(x > y) # Greater than 
print(x < y) # Less than
print(x >= y) # Greater than or equal to
print(x <= y) # Less than or equal to
print(x == y) # Equal to
print(x != y) # Not equal to
print(x is y) # Identity operator
print(x is not y) # Not identity operator
print(x in [1, 2, 3, 4, 5]) # Membership operator
print(x not in [1, 2, 3, 4, 5]) # Not membership operator

a = 30
b = 60 
out = (a > b) and (a < b)
print(out)

out = (a > b) or (a < b)
